#!/usr/bin/env python3
"""Mini Connected Papers — local web UI.

Run:  python3 app.py [--port 8000] [--api-key KEY] [--mailto you@example.com]
Then open http://127.0.0.1:8000, search keywords, click a paper, get the graph.
"""

import argparse
import json
import os
import re
import threading
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import parse_qs, urlparse

import pipeline as P

STATE = {"cache": {}, "lock": threading.Lock(), "client": None}

HISTORY_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "history.json")
HISTORY_MAX = 30


def load_history():
    try:
        with open(HISTORY_FILE) as fh:
            data = json.load(fh)
            return data if isinstance(data, list) else []
    except (OSError, ValueError):
        return []


def save_history(entries):
    with open(HISTORY_FILE, "w") as fh:
        json.dump(entries, fh, indent=1, ensure_ascii=False)


def record_history(result, opts):
    entry = {
        "ts": int(time.time()),
        "query": result["seed"]["openalex_id"],
        "title": result["seed"]["title"],
        "year": result["seed"]["year"],
        "first_author": result["seed"]["first_author"],
        "pool": result["stats"]["pool"],
        "edges": result["stats"]["edges"],
        "depth": opts["depth"],
    }
    with STATE["lock"]:
        entries = [e for e in load_history() if e.get("query") != entry["query"]]
        entries.insert(0, entry)
        save_history(entries[:HISTORY_MAX])


def do_search(q, per_page=20):
    d = STATE["client"].get(
        "/works",
        {"filter": f"title_and_abstract.search:{q}", "per-page": per_page,
         "select": "id,display_name,publication_year,cited_by_count,"
                   "primary_location,doi,abstract_inverted_index,authorships"})
    results = []
    for w in d.get("results") or []:
        abstract = P.uninvert(w.get("abstract_inverted_index"))
        results.append({
            "id": P.oa_id(w),
            "title": w.get("display_name"),
            "year": w.get("publication_year"),
            "citations": w.get("cited_by_count") or 0,
            "venue": P.work_venue(w),
            "url": P.work_url(w),
            "abstract": abstract[:300],
            "first_author": P.last_name(P.first_author_name(w)),
        })
    return {"results": results}


def do_graph(req):
    query = (req.get("query") or "").strip()
    opts = {"pool": int(req.get("pool", 80)), "depth": int(req.get("depth", 1)),
            "min_sim": float(req.get("min_sim", 0.12)), "max_citers": 300, "max_edges": 500}
    key = (query, opts["pool"], opts["depth"], opts["min_sim"])
    with STATE["lock"]:
        cached = STATE["cache"].get(key)
    if cached is not None:
        record_history(cached, opts)
        return cached
    result = P.build(STATE["client"], query, **opts)
    with STATE["lock"]:
        STATE["cache"][key] = result
        if len(STATE["cache"]) > 6:
            STATE["cache"].pop(next(iter(STATE["cache"])))
    record_history(result, opts)
    return result


class Handler(BaseHTTPRequestHandler):
    def _send(self, code, body, ctype="application/json; charset=utf-8"):
        data = body if isinstance(body, bytes) else json.dumps(body).encode("utf-8")
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(data)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(data)

    def do_GET(self):
        u = urlparse(self.path)
        if u.path in ("/", "/index.html"):
            path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "index.html")
            with open(path, "rb") as fh:
                self._send(200, fh.read(), "text/html; charset=utf-8")
        elif u.path == "/api/search":
            q = parse_qs(u.query).get("q", [""])[0].strip()
            per = min(int(parse_qs(u.query).get("per_page", ["20"])[0]), 50)
            if not q:
                return self._send(400, {"error": "missing q"})
            try:
                self._send(200, do_search(q, per))
            except Exception as err:  # noqa: BLE001
                self._send(502, {"error": str(err)})
        elif u.path == "/api/bibtex":
            qs = parse_qs(u.query)
            ids = [x.strip() for x in qs.get("ids", [""])[0].split(",") if x.strip()][:200]
            name = re.sub(r"[^a-z0-9_-]", "_",
                          qs.get("name", ["references"])[0].strip() or "references")[:60]
            if not ids:
                return self._send(400, {"error": "missing ids"})
            try:
                bib = P.fetch_bibtex(STATE["client"], ids)
                data = ("# Generated by Mini Connected Papers (OpenAlex)\n\n" + bib).encode("utf-8")
                self.send_response(200)
                self.send_header("Content-Type", "application/x-bibtex; charset=utf-8")
                self.send_header("Content-Disposition", f'attachment; filename="{name}.bib"')
                self.send_header("Content-Length", str(len(data)))
                self.end_headers()
                self.wfile.write(data)
            except Exception as err:  # noqa: BLE001
                self._send(500, {"error": str(err)})
        elif u.path == "/api/history":
            with STATE["lock"]:
                self._send(200, {"items": load_history()})
        else:
            self._send(404, {"error": "not found"})

    def do_DELETE(self):
        u = urlparse(self.path)
        if u.path == "/api/history":
            with STATE["lock"]:
                entries = load_history()
                keep = parse_qs(u.query).get("id", [None])[0]
                entries = ([e for e in entries if e.get("query") != keep]
                           if keep else [])
                save_history(entries)
                self._send(200, {"items": entries})
        else:
            self._send(404, {"error": "not found"})

    def do_POST(self):
        u = urlparse(self.path)
        if u.path == "/api/graph":
            try:
                n = int(self.headers.get("Content-Length", 0))
                req = json.loads(self.rfile.read(n) or b"{}")
                if not (req.get("query") or "").strip():
                    return self._send(400, {"error": "missing query"})
                self._send(200, do_graph(req))
            except Exception as err:  # noqa: BLE001
                self._send(500, {"error": str(err)})
        else:
            self._send(404, {"error": "not found"})

    def log_message(self, fmt, *args):
        print(f"[{self.log_date_time_string()}] {fmt % args}", flush=True)


def main():
    ap = argparse.ArgumentParser(description="Mini Connected Papers web UI.")
    ap.add_argument("--port", type=int, default=8000)
    ap.add_argument("--mailto", help="your email for OpenAlex's polite pool")
    ap.add_argument("--api-key", default=os.environ.get("OPENALEX_API_KEY"),
                    help="OpenAlex API key (or set OPENALEX_API_KEY)")
    args = ap.parse_args()
    STATE["client"] = P.Client(mailto=args.mailto, api_key=args.api_key)
    server = ThreadingHTTPServer(("127.0.0.1", args.port), Handler)
    print(f"Mini Connected Papers:  http://127.0.0.1:{args.port}   (Ctrl-C to stop)")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nstopped.")


if __name__ == "__main__":
    main()
